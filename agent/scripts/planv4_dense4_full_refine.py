#!/usr/bin/env python3
"""Continue the PlanV4 dense-only ablation with full-video VLM selection/refinement.

Round 0 is generated by generate_planv4_dense4.py.  Every subsequent round
contains four *full* 81-frame / 50-step videos.  The VLM scores all four full
storyboards.  A score >= threshold terminates the prompt; otherwise DeepSeek
receives the structured VLM evidence and writes four conservative rewrites for
the next round.  No sparse generation or sparse-to-full handoff is used.
"""
from __future__ import annotations

import argparse
import base64
import concurrent.futures as cf
import importlib.util
import json
import os
import shutil
import sys
import time
import urllib.error
import urllib.request
from datetime import datetime, timezone
from pathlib import Path
from typing import Any

PROJECT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(PROJECT))
from sparsemac.deepseek_client import DeepSeekClient
from sparsemac.planner import seed_pool
from sparsemac.vision import make_storyboard

GEN_PATH = PROJECT / "scripts" / "generate_planv4_dense4.py"
_spec = importlib.util.spec_from_file_location("planv4_dense4_generator", GEN_PATH)
gen = importlib.util.module_from_spec(_spec)
assert _spec and _spec.loader
_spec.loader.exec_module(gen)

DEFAULT_ROOT = PROJECT / "runs/ablation/planv4-dense4-full-difficult175"

VLM_PROMPT = """You are a strict semantic evaluator for a text-to-video benchmark.
Judge only the visible evidence in this 11-frame storyboard. The source is a
full 81-frame video, but you must not infer unshown events.

Evaluate semantic compliance only. Do not penalize ordinary visual blur,
compression, stylization, or minor artifacts unless they make a prompt-critical
object, attribute, count, relation, interaction, action, or state transition
unjudgeable. Do not reward an entity merely for appearing: score the
prompt-discriminative requirement it serves.

Original benchmark prompt:
{original_prompt}

Prompt used for this candidate:
{candidate_prompt}

VQA checks and normalized weights:
{checks}

Return JSON only with exactly these keys:
- score: normalized weighted score in [0,1]
- vqa_results: list of {{question, vqa_score, weight, reason}}
- failure_reasons: list of concrete visible failures
- evidence: concise visible evidence
- recommendation: concise fix suggestion
- success_or_failure_reason: concise overall reason
Score every listed check exactly once. vqa_score is an integer 0..100. For
scores <82, reason must be concrete and grounded in the storyboard.
"""

REFINE_PROMPT = """You are SparseMAC's analyzer for a dense-only PlanV4 ablation.
All candidates in every round are complete 81-frame videos. The full-video VLM
has already supplied structured evidence. The current best score is below the
acceptance threshold, so propose exactly {budget} conservative prompt rewrites
for one more full-video round.

Hard rules:
- Preserve benchmark semantics exactly: entities, counts, attributes, relation,
  action/motion, interaction, and state change.
- Do not add style, camera, lighting, background, or unrelated events.
- Target only the concrete low-score VQA evidence.
- Each rewrite must be English and distinct.

Input JSON:
{payload}

Return JSON only with keys: reason, failure_focus, rewrite_hints, next_prompts.
next_prompts must be exactly {budget} strings.
"""


def now() -> str:
    return datetime.now(timezone.utc).isoformat()


def read_json(path: Path, default: Any = None) -> Any:
    try:
        return json.loads(path.read_text(encoding="utf-8"))
    except Exception:
        return default


def write_json(path: Path, value: Any) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    tmp = path.with_suffix(path.suffix + ".tmp")
    tmp.write_text(json.dumps(value, indent=2, ensure_ascii=False), encoding="utf-8")
    os.replace(tmp, path)


def norm_score(value: Any) -> float:
    score = float(value)
    if score > 1:
        score /= 100.0
    if not 0.0 <= score <= 1.0:
        raise ValueError(f"score outside [0,1]: {value!r}")
    return score


def vlm_config() -> tuple[str, str, str]:
    base = os.environ.get("VQQA_VLM_BASE_URL", "http://127.0.0.1:18080/v1").rstrip("/")
    model = os.environ.get("VQQA_VLM_MODEL", "gpt-5.6-luna")
    key = os.environ.get("VQQA_VLM_API_KEY")
    if not key:
        raise RuntimeError("VQQA_VLM_API_KEY is required; refusing to silently fall back to another VLM.")
    return base, model, key


def parse_content(body: dict[str, Any]) -> str:
    choices = body.get("choices") or []
    message = choices[0].get("message", {}) if choices and isinstance(choices[0], dict) else {}
    content = message.get("content") or body.get("output_text") or ""
    if isinstance(content, list):
        content = "\n".join(str(x.get("text") or x.get("content") or "") if isinstance(x, dict) else str(x) for x in content)
    return str(content).strip()


def parse_json_text(text: str) -> dict[str, Any]:
    text = text.strip()
    if text.startswith("```"):
        text = text.strip("`").strip()
        if text.lower().startswith("json"):
            text = text[4:].strip()
    try:
        value = json.loads(text)
    except json.JSONDecodeError:
        start, end = text.find("{"), text.rfind("}")
        if start < 0 or end <= start:
            raise
        value = json.loads(text[start : end + 1])
    if not isinstance(value, dict):
        raise ValueError("VLM reply JSON is not an object")
    return value


def judge_candidate(candidate: dict[str, Any], original_prompt: str, plan: dict[str, Any]) -> dict[str, Any]:
    out = Path(candidate["judge_json"])
    prior = read_json(out)
    if isinstance(prior, dict):
        try:
            prior["score"] = norm_score(prior.get("score"))
            return prior
        except Exception:
            pass
    storyboard = Path(candidate["storyboard"])
    if not storyboard.exists():
        make_storyboard(candidate["video"], str(storyboard), frames=11)
    checks_map = plan.get("vqa_scores") if isinstance(plan.get("vqa_scores"), dict) else {}
    checks = "\n".join(f"- {q} (weight: {w})" for q, w in checks_map.items())
    if not checks:
        raise RuntimeError("PlanV4 plan is missing vqa_scores")
    prompt = VLM_PROMPT.format(original_prompt=original_prompt, candidate_prompt=candidate["prompt"], checks=checks)
    base, model, key = vlm_config()
    image = base64.b64encode(storyboard.read_bytes()).decode("ascii")
    payload = {
        "model": model,
        "messages": [{"role": "user", "content": [
            {"type": "text", "text": prompt},
            {"type": "image_url", "image_url": {"url": f"data:image/jpeg;base64,{image}", "detail": "high"}},
        ]}],
        "response_format": {"type": "json_object"},
        "temperature": 0.0,
        "max_tokens": 1800,
    }
    errors: list[str] = []
    for attempt in range(4):
        req = urllib.request.Request(f"{base}/chat/completions", data=json.dumps(payload).encode(), headers={"Authorization": f"Bearer {key}", "Content-Type": "application/json"}, method="POST")
        try:
            with urllib.request.urlopen(req, timeout=180) as resp:
                data = parse_json_text(parse_content(json.loads(resp.read().decode("utf-8", errors="replace"))))
            data["score"] = norm_score(data.get("score"))
            data.update({"candidate_id": candidate["candidate_id"], "model": model, "judged_at": now()})
            write_json(out, data)
            return data
        except Exception as exc:
            errors.append(f"attempt {attempt + 1}: {type(exc).__name__}: {exc}")
            time.sleep(4 * (attempt + 1))
    raise RuntimeError("VLM judging failed after 4 attempts: " + " | ".join(errors))


def candidate_records(prompt_root: Path, round_index: int) -> list[dict[str, Any]]:
    base = prompt_root if round_index == 0 else prompt_root / f"round_{round_index:02d}"
    records = read_json(base / "candidates.json")
    if not isinstance(records, list):
        raise FileNotFoundError(f"missing candidates.json: {base}")
    output = []
    for c in records:
        if not isinstance(c, dict):
            continue
        c = dict(c)
        c["judge_json"] = str(Path(c["metadata"]).with_name("full_visual_judge.json"))
        output.append(c)
    if len(output) != 4:
        raise RuntimeError(f"expected four candidates for round {round_index}, got {len(output)}")
    return output


def generate_round(item: dict[str, Any], plan: dict[str, Any], prompt_root: Path, round_index: int, prompts: list[str], seeds: list[int], args: argparse.Namespace) -> list[dict[str, Any]]:
    if len(prompts) != 4 or len(seeds) != 4:
        raise ValueError("dense full round requires exactly four prompts and four seeds")
    base = prompt_root / f"round_{round_index:02d}"
    candidates: list[dict[str, Any]] = []
    for idx, (prompt, seed) in enumerate(zip(prompts, seeds)):
        d = base / "candidates" / f"candidate_{idx:02d}"
        candidates.append({
            "candidate_id": f"candidate_{idx:02d}", "candidate_index": idx, "prompt": prompt, "seed": int(seed),
            "video": str(d / "video.mp4"), "storyboard": str(d / "storyboard_11.jpg"),
            "log": str(d / "generate.log"), "metadata": str(d / "metadata.json"), "status": "pending",
        })
    with cf.ThreadPoolExecutor(max_workers=4) as pool:
        futures = [pool.submit(gen.generate_one, candidate=c, gpu=args.gpus[i], args=args) for i, c in enumerate(candidates)]
        candidates = [f.result() for f in futures]
    candidates.sort(key=lambda x: x["candidate_index"])
    write_json(base / "candidates.json", candidates)
    write_json(base / "generation_result.json", {"round_index": round_index, "generated_at": now(), "candidates": candidates})
    if any(c.get("status") not in {"ok", "skipped_valid"} for c in candidates):
        raise RuntimeError(f"round {round_index} has failed full candidates")
    return candidates


def analyze(original_prompt: str, plan: dict[str, Any], history: list[dict[str, Any]], best: dict[str, Any]) -> dict[str, Any]:
    client = DeepSeekClient(model=os.environ.get("DENSE4_ANALYZER_MODEL", "deepseek-v4-flash"))
    if not client.available:
        raise RuntimeError(client.last_error or "DeepSeek analyzer unavailable")
    payload = {"original_prompt": original_prompt, "candidate_budget": 4, "round_history": history, "current_best_candidate": best}
    parsed, raw = client.generate_json(REFINE_PROMPT.format(budget=4, payload=json.dumps(payload, ensure_ascii=False, indent=2)), max_tokens=2000, temperature=0.2)
    if not isinstance(parsed, dict):
        raise RuntimeError("DeepSeek analyzer returned invalid JSON: " + str(raw or client.last_error)[:800])
    prompts = parsed.get("next_prompts")
    if not isinstance(prompts, list):
        raise RuntimeError("DeepSeek analyzer response missing next_prompts")
    prompts = [str(p).strip() for p in prompts if str(p).strip()]
    if len(prompts) != 4:
        raise RuntimeError(f"DeepSeek analyzer must return exactly 4 rewrites, got {len(prompts)}")
    parsed["next_prompts"] = prompts
    parsed["model"] = client.model
    parsed["raw"] = raw
    return parsed


def materialize_selection(prompt_root: Path, original_prompt: str, rounds: list[dict[str, Any]], best: dict[str, Any], threshold: float) -> None:
    video = Path(best["candidate"]["video"])
    selected = prompt_root / "selected"
    selected.mkdir(parents=True, exist_ok=True)
    link = selected / "video.mp4"
    if link.exists() or link.is_symlink(): link.unlink()
    link.symlink_to(os.path.relpath(video, selected))
    source_story = Path(best["candidate"]["storyboard"])
    story = selected / "storyboard_11.jpg"
    if story.exists() or story.is_symlink(): story.unlink()
    story.symlink_to(os.path.relpath(source_story, selected))
    result = {
        "status": "accepted" if best["score"] >= threshold else "max_rounds_below_threshold",
        "original_prompt": original_prompt, "threshold": threshold, "selected_round": best["round_index"],
        "selected_candidate_id": best["candidate"]["candidate_id"], "selected_score": best["score"],
        "selected_prompt": best["candidate"]["prompt"], "selected_seed": best["candidate"]["seed"],
        "selected_video": str(link), "rounds": rounds, "completed_at": now(),
    }
    write_json(prompt_root / "final_selection.json", result)


def process_one(item: dict[str, Any], args: argparse.Namespace) -> dict[str, Any]:
    prompt_root = args.run_root / "trajectories" / item["category_key"] / item["prompt_id"]
    final = read_json(prompt_root / "final_selection.json")
    if isinstance(final, dict) and Path(final.get("selected_video", "")).exists():
        return {"prompt_id": item["prompt_id"], "status": "skipped_complete"}
    plan = read_json(prompt_root / "plan.json")
    if not isinstance(plan, dict):
        plan = gen.plan_for(args.plan_dir / f"{item['prompt_id']}.json")
    original = item["prompt"]
    rounds: list[dict[str, Any]] = []
    best_all: dict[str, Any] | None = None
    for ri in range(args.max_rounds):
        if ri == 0:
            candidates = candidate_records(prompt_root, 0)
        else:
            prev_best = best_all
            assert prev_best is not None
            analyzer = analyze(original, plan, rounds, {"round_index": prev_best["round_index"], "candidate_id": prev_best["candidate"]["candidate_id"], "prompt": prev_best["candidate"]["prompt"], "seed": prev_best["candidate"]["seed"], "score": prev_best["score"], "vqa_feedback": prev_best["judgment"].get("vqa_results", [])})
            round_dir = prompt_root / f"round_{ri - 1:02d}"
            write_json(round_dir / "analyzer_refine.json", analyzer)
            prompts = analyzer["next_prompts"]
            # Preserve a promising seed; otherwise genuinely resample four seeds.
            if prev_best["score"] >= args.keep_seed_threshold:
                seeds = [int(prev_best["candidate"]["seed"])] * 4
            else:
                seeds = seed_pool(original + "\n" + json.dumps(prompts, ensure_ascii=False), ri, 4)
            generate_round(item, plan, prompt_root, ri, prompts, seeds, args)
            candidates = candidate_records(prompt_root, ri)
        judged: list[dict[str, Any]] = []
        for candidate in candidates:
            judgment = judge_candidate(candidate, original, plan)
            judged.append({"candidate": candidate, "score": norm_score(judgment["score"]), "judgment": judgment})
        best_round = max(judged, key=lambda x: x["score"])
        if best_all is None or best_round["score"] > best_all["score"]:
            best_all = {**best_round, "round_index": ri}
        record = {"round_index": ri, "candidates": [{"candidate_id": x["candidate"]["candidate_id"], "prompt": x["candidate"]["prompt"], "seed": x["candidate"]["seed"], "score": x["score"], "judge_json": x["candidate"]["judge_json"]} for x in judged], "best_candidate_id": best_round["candidate"]["candidate_id"], "best_score": best_round["score"], "best_prompt": best_round["candidate"]["prompt"], "best_seed": best_round["candidate"]["seed"]}
        rounds.append(record)
        write_json(prompt_root / "trajectory.json", {"original_prompt": original, "rounds": rounds, "best_so_far": {"round_index": best_all["round_index"], "candidate_id": best_all["candidate"]["candidate_id"], "score": best_all["score"]}, "updated_at": now()})
        if best_round["score"] >= args.threshold:
            break
    assert best_all is not None
    materialize_selection(prompt_root, original, rounds, best_all, args.threshold)
    return {"prompt_id": item["prompt_id"], "status": "accepted" if best_all["score"] >= args.threshold else "max_rounds_below_threshold", "score": best_all["score"], "rounds": len(rounds)}


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--run-root", type=Path, default=DEFAULT_ROOT)
    ap.add_argument("--source-manifest", type=Path, default=gen.DEFAULT_MANIFEST)
    ap.add_argument("--plan-dir", type=Path, default=gen.DEFAULT_PLAN_DIR)
    ap.add_argument("--generator-root", type=Path, default=gen.DEFAULT_GENERATOR)
    ap.add_argument("--ckpt-dir", type=Path, default=gen.DEFAULT_CKPT)
    ap.add_argument("--python-bin", type=Path, default=gen.DEFAULT_PYTHON)
    ap.add_argument("--gpus", default="0,1,2,3")
    ap.add_argument("--steps", type=int, default=50)
    ap.add_argument("--size", default="832*480")
    ap.add_argument("--shift", type=float, default=8.0)
    ap.add_argument("--guide-scale", type=float, default=6.0)
    ap.add_argument("--max-rounds", type=int, default=3)
    ap.add_argument("--threshold", type=float, default=0.70)
    ap.add_argument("--keep-seed-threshold", type=float, default=0.60)
    ap.add_argument("--start-index", type=int, default=0)
    ap.add_argument("--limit", type=int)
    args = ap.parse_args()
    args.gpus = [int(x) for x in args.gpus.split(",") if x.strip()]
    if len(args.gpus) != 4: raise SystemExit("requires exactly four GPUs")
    manifest = read_json(args.source_manifest)
    items = list(manifest["items"])[args.start_index:]
    if args.limit is not None: items = items[:args.limit]
    summary_path = args.run_root / "full_refine_summary.jsonl"
    for n, item in enumerate(items, 1):
        try:
            result = process_one(item, args)
        except Exception as exc:
            result = {"prompt_id": item["prompt_id"], "status": "failed", "error": f"{type(exc).__name__}: {exc}"}
        result["processed_at"] = now()
        with summary_path.open("a", encoding="utf-8") as f: f.write(json.dumps(result, ensure_ascii=False) + "\n")
        print(f"[{n}/{len(items)}] {item['prompt_id']} {result['status']} score={result.get('score')}", flush=True)
    return 0

if __name__ == "__main__":
    raise SystemExit(main())
